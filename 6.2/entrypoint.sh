#!/bin/sh
#
# Boot order: make the writable trees writable, write the overrides, run 6.2's own
# installer once if the site is not installed yet, seed it, then hand off to
# Apache.
#
# The middle is what is new. Every older entrypoint wrote localconf.php from a
# heredoc and built the schema itself. 6.2 cannot be set up that way (install.php
# says why), so on first boot this starts Apache in the background, has
# install.php walk the step installer through it over loopback, stops Apache
# again, and only then starts it in the foreground for good.
set -eu

DOCROOT=/var/www/html
TYPO3CONF="$DOCROOT/typo3conf"

: "${TYPO3_DB_HOST:=db}"
: "${TYPO3_DB_NAME:=typo3}"
: "${TYPO3_DB_USER:=typo3}"
: "${TYPO3_DB_PASSWORD:=typo3}"
: "${TYPO3_SITENAME:=TYPO3 6.2.31}"
: "${TYPO3_ADMIN_USER:=admin}"
: "${TYPO3_ADMIN_PASSWORD:=password}"
: "${TYPO3_BEHIND_TLS:=0}"

export TYPO3_DB_HOST TYPO3_DB_NAME TYPO3_DB_USER TYPO3_DB_PASSWORD TYPO3_SITENAME \
       TYPO3_ADMIN_USER TYPO3_ADMIN_PASSWORD

case "$TYPO3_BEHIND_TLS" in
    0|1) ;;
    *)
        echo "[entrypoint] ERROR: TYPO3_BEHIND_TLS must be 0 or 1, got '$TYPO3_BEHIND_TLS'" >&2
        exit 1
        ;;
esac

# The four document-root trees. The installer creates what it wants below them
# itself (its folder-structure step, EnvironmentAndFolders), so only ownership is
# settled here: it runs inside Apache, as www-data.
for dir in typo3conf typo3temp uploads fileadmin; do
    mkdir -p "$DOCROOT/$dir"
done
chown -R www-data:www-data "$DOCROOT/typo3conf" "$DOCROOT/typo3temp" "$DOCROOT/fileadmin" "$DOCROOT/uploads"

# --- AdditionalConfiguration.php --------------------------------------------
# 6.2 loads this after LocalConfiguration.php on every request, the Install Tool's
# included, and nothing in 6.2 writes it. So it carries what this stack decides,
# while LocalConfiguration.php stays exactly what the installer wrote.
ADDITIONAL="$TYPO3CONF/AdditionalConfiguration.php"
if [ ! -f "$ADDITIONAL" ]; then
    echo "[entrypoint] writing typo3conf/AdditionalConfiguration.php"
    cat > "$ADDITIONAL" <<'EOF'
<?php
// Generated by 6.2/entrypoint.sh on first boot. It holds this stack's
// decisions; LocalConfiguration.php beside it is the installer's own output.

// 4.5's trustedHostsPattern finding, in 6.2. The default, SERVER_NAME, compares the Host header with
// SERVER_NAME and its port with SERVER_PORT, or with 443 or 80 when the header
// names none (GeneralUtility.php:3674-3683). Behind the loopback proxy the header
// carries :8062 while Apache listens on 80, and behind a TLS proxy with
// TYPO3_BEHIND_TLS=1 TYPO3 expects 443. Either way every request but the Install
// Tool's would throw. '.*' is 4.5's recorded decision, for 4.5's reason: the stack
// answers on loopback only and has no egress.
$GLOBALS['TYPO3_CONF_VARS']['SYS']['trustedHostsPattern'] = '.*';

// Fixed, for the cHash reason every other stack gives. The installer generates a
// random one into LocalConfiguration.php (SilentConfigurationUpgradeService);
// this overrides it, so two builds render the same frontend URLs.
$GLOBALS['TYPO3_CONF_VARS']['SYS']['encryptionKey'] = '5c1f9a7e3b2d8c6a0e4f7b1d9c3a5e8f2b6d0a4c7e1f3b9d5a8c2e6f0b4d7a1c3e9f5b2d8a6c0e4f7b1d3a9c5e8f2b6';
EOF
    chown www-data:www-data "$ADDITIONAL"
    chmod 0640 "$ADDITIONAL"
fi

# --- the Install Tool --------------------------------------------------------
# 4.5's arrangement, and needed earlier here: the installer itself runs through
# the Install Tool. 6.2 would also accept a FIRST_INSTALL file in the document
# root, but only while typo3conf/ does not exist yet
# (EnableFileService::isFirstInstallAllowed(), EnableFileService.php:40-43), and
# here it always exists, because compose.yaml mounts a volume there. KEEP_FILE
# because the file otherwise expires after an hour (:35) and because the
# installer's last step deletes it unless it says so (DefaultConfiguration.php,
# execute()).
ENABLE_FILE="$TYPO3CONF/ENABLE_INSTALL_TOOL"
if [ ! -f "$ENABLE_FILE" ]; then
    printf 'KEEP_FILE\n' > "$ENABLE_FILE"
    chown www-data:www-data "$ENABLE_FILE"
fi

# --- install, once -----------------------------------------------------------
wait_for_port_80() {
    php -r 'for ($i = 0; $i < 60; $i++) { $s = @fsockopen("127.0.0.1", 80); if ($s) { exit(0); } usleep(500000); } exit(1);'
}

wait_for_apache_to_stop() {
    php -r 'for ($i = 0; $i < 60; $i++) { $s = @fsockopen("127.0.0.1", 80); if (!$s) { exit(0); } fclose($s); usleep(500000); } exit(1);'
}

if [ ! -f "$TYPO3CONF/LocalConfiguration.php" ]; then
    php /usr/local/share/typo3/provision.php preflight

    # -DTYPO3_INSTALLING makes this Apache answer loopback only
    # (apache-typo3.conf), because until the installer has finished, its Install
    # Tool asks nobody for a password.
    echo "[entrypoint] starting apache in the background for the installer, loopback only"
    # apache2 itself rather than apache2ctl, so the define reaches it for certain:
    # sourcing envvars first is what apache2-foreground does too. In a subshell, so
    # the variables envvars exports do not leak into the rest of this script.
    (. /etc/apache2/envvars && mkdir -p "$APACHE_RUN_DIR" "$APACHE_LOCK_DIR" "$APACHE_LOG_DIR" && apache2 -DTYPO3_INSTALLING -k start)
    if ! wait_for_port_80; then
        echo "[entrypoint] ERROR: apache did not come up for the installer" >&2
        exit 1
    fi

    status=0
    php /usr/local/share/typo3/install.php || status=$?

    (. /etc/apache2/envvars && apache2 -k stop) || true
    wait_for_apache_to_stop || true
    if [ "$status" -ne 0 ]; then
        echo "[entrypoint] ERROR: the installer did not finish" >&2
        exit "$status"
    fi
fi

# Idempotent, so it runs on every boot: it seeds once and says so afterwards.
php /usr/local/share/typo3/provision.php seed

# --- serve -----------------------------------------------------------------
if [ "$TYPO3_BEHIND_TLS" = 1 ]; then
    echo "[entrypoint] starting apache, told it sits behind TLS (HTTPS=on)"
    exec apache2-foreground -DTYPO3_BEHIND_TLS
fi

echo "[entrypoint] starting apache"
exec apache2-foreground
