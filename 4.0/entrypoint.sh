#!/bin/sh
#
# Boot order: make the writable trees writable, generate localconf.php, provision
# the database, then hand off to Apache.
#
# Same shape as 3.8/entrypoint.sh, whose comments carry the reasons for the
# parts that are identical. 4.0 sits between 3.8 and 4.5 and takes one thing from
# each side: 3.8's latin1 and its Install Tool, 4.5's switch for running behind
# TLS. docs/how-it-works.md says why each side won.
set -eu

DOCROOT=/var/www/html

: "${TYPO3_DB_HOST:=db}"
: "${TYPO3_DB_NAME:=typo3}"
: "${TYPO3_DB_USER:=typo3}"
: "${TYPO3_DB_PASSWORD:=typo3}"
: "${TYPO3_SITENAME:=TYPO3 4.0.13}"
: "${TYPO3_INSTALL_PASSWORD:=joh316}"
: "${TYPO3_PROVISION:=auto}"
: "${TYPO3_BEHIND_TLS:=0}"

export TYPO3_DB_HOST TYPO3_DB_NAME TYPO3_DB_USER TYPO3_DB_PASSWORD TYPO3_PROVISION

case "$TYPO3_PROVISION" in
    auto|wizard) ;;
    *)
        echo "[entrypoint] ERROR: TYPO3_PROVISION must be 'auto' or 'wizard', got '$TYPO3_PROVISION'" >&2
        exit 1
        ;;
esac

case "$TYPO3_BEHIND_TLS" in
    0|1) ;;
    *)
        echo "[entrypoint] ERROR: TYPO3_BEHIND_TLS must be 0 or 1, got '$TYPO3_BEHIND_TLS'" >&2
        exit 1
        ;;
esac

# The trees the Install Tool's directory check requires
# (typo3/sysext/install/mod/class.tx_install.php:1695-1712). 4.5's typo3temp/locks/
# is not among them; it is a 4.5 addition. As in 3.8 and 4.5, nothing inside the
# source tree has to be writable: 4.0 has no typo3/temp/.
for dir in typo3conf typo3temp/pics typo3temp/temp typo3temp/llxml typo3temp/cs \
           typo3temp/GB fileadmin/_temp_ uploads/pics uploads/media uploads/tf; do
    mkdir -p "$DOCROOT/$dir"
done
chown -R www-data:www-data "$DOCROOT/typo3conf" "$DOCROOT/typo3temp" "$DOCROOT/fileadmin" "$DOCROOT/uploads"

# --- localconf.php ---------------------------------------------------------
# t3lib/config_default.php:270 die()s if it is absent, so it has to exist before
# anything runs, the 1-2-3 wizard included. Written once and then left alone,
# because the Install Tool edits this same file.
LOCALCONF="$DOCROOT/typo3conf/localconf.php"
if [ ! -f "$LOCALCONF" ]; then
    INSTALL_HASH=$(printf '%s' "$TYPO3_INSTALL_PASSWORD" | md5sum | cut -d' ' -f1)

    if [ "$TYPO3_PROVISION" = wizard ]; then
        echo "[entrypoint] writing stub typo3conf/localconf.php (wizard mode)"
        cat > "$LOCALCONF" <<EOF
<?php
// Generated by 4.0/entrypoint.sh on first boot, in wizard mode.
// Deliberately minimal: the 1-2-3 install wizard fills in the rest, including
// compat_version, which its step 1 writes (class.tx_install.php:681).
\$TYPO3_CONF_VARS['BE']['installToolPassword'] = '${INSTALL_HASH}';
?>
EOF
    else
        echo "[entrypoint] writing typo3conf/localconf.php"
        cat > "$LOCALCONF" <<EOF
<?php
// Generated by 4.0/entrypoint.sh on first boot.
// Edit freely — this file is only created when it does not already exist.

\$typo_db_username = '${TYPO3_DB_USER}';
\$typo_db_password = '${TYPO3_DB_PASSWORD}';
\$typo_db_host     = '${TYPO3_DB_HOST}';
\$typo_db          = '${TYPO3_DB_NAME}';

\$TYPO3_CONF_VARS['SYS']['sitename'] = '${TYPO3_SITENAME}';
\$TYPO3_CONF_VARS['BE']['installToolPassword'] = '${INSTALL_HASH}';

// What the 1-2-3 wizard writes for a new site (class.tx_install.php:681). Unlike
// 4.5, nothing dies without it: the default, '3.8' (config_default.php:60), only
// makes the backend warn that the site "is not configured for the TYPO3 version
// it is running" (t3lib/class.t3lib_befunc.php:3529) and keeps 3.8's frontend
// JavaScript (class.tslib_fe.php:1785). A fresh 4.0 says 4.0.
\$TYPO3_CONF_VARS['SYS']['compat_version'] = '4.0';

// No forceCharset and no setDBinit, on purpose. Both default to empty
// (config_default.php:141, :88), which is what makes a fresh 4.0 an ISO-8859-1
// site: the backend takes its charset from the user's language, iso-8859-1 for
// English (typo3/sysext/lang/lang.php:93), the frontend from defaultCharSet,
// iso-8859-1 (class.tslib_fe.php:348), and the connection from the server,
// because t3lib_db sends nothing. Setting them
// to UTF-8 is what 4.0 sites did by hand, later; it is not how one shipped.

// Fixed on purpose, and not a secret — same argument as 3.8: TYPO3 salts
// cHash values with this, and a generated key would put a different hash into
// every frontend URL on every fresh boot.
\$TYPO3_CONF_VARS['SYS']['encryptionKey'] = '7d2a9f4c1e8b6d3a0f5c9e2b7a4d1f8c3e6b0a9d5f2c8e1b4a7d0c3f6e9b2a5d';

// Image processing. 4.0 still ships the 2005 defaults: ImageMagick 4.2.9 under
// /usr/X11R6/bin (config_default.php:39), whose compositing tool was "combine"
// (:50). Debian ships ImageMagick 6 in /usr/bin, where it is "composite", and
// 4.0 knows im6 by name (:42).
\$TYPO3_CONF_VARS['GFX']['im_path']             = '/usr/bin/';
\$TYPO3_CONF_VARS['GFX']['im_path_lzw']         = '/usr/bin/';
\$TYPO3_CONF_VARS['GFX']['im_version_5']        = 'im6';
\$TYPO3_CONF_VARS['GFX']['im_combine_filename'] = 'composite';

// Upstream also lists pdf and ai. Dropped for 3.8's reason: Debian's ImageMagick
// policy denies the PS and PDF coders and no ghostscript is installed, so they
// would be advertised and broken.
\$TYPO3_CONF_VARS['GFX']['imagefile_ext'] = 'gif,jpg,jpeg,tif,bmp,pcx,tga,png';

// PHP 5.6 bundles GD 2.x, which is what gdlib_2 asks about; 4.0 still defaults it
// off (:36). GIF output stays on, as in 3.8.
\$TYPO3_CONF_VARS['GFX']['gdlib_2'] = 1;
?>
EOF
    fi

    chown www-data:www-data "$LOCALCONF"
    chmod 0640 "$LOCALCONF"
fi

# --- database --------------------------------------------------------------
php /usr/local/share/typo3/provision.php

# --- serve -----------------------------------------------------------------
if [ "$TYPO3_BEHIND_TLS" = 1 ]; then
    echo "[entrypoint] starting apache, told it sits behind TLS (HTTPS=on)"
    exec apache2-foreground -DTYPO3_BEHIND_TLS
fi

echo "[entrypoint] starting apache"
exec apache2-foreground
