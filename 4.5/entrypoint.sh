#!/bin/sh
#
# Boot order: make the writable trees writable, generate localconf.php, provision
# the database, then hand off to Apache.
#
# Same shape as 3.8/entrypoint.sh. What 4.5 adds is all in localconf.php,
# and every addition is a default that a fresh 4.5 site cannot run on — see the
# comments there and docs/how-it-works.md.
set -eu

DOCROOT=/var/www/html

: "${TYPO3_DB_HOST:=db}"
: "${TYPO3_DB_NAME:=typo3}"
: "${TYPO3_DB_USER:=typo3}"
: "${TYPO3_DB_PASSWORD:=typo3}"
: "${TYPO3_SITENAME:=TYPO3 4.5.40}"
: "${TYPO3_INSTALL_PASSWORD:=joh316}"
: "${TYPO3_PROVISION:=auto}"
: "${TYPO3_BEHIND_TLS:=0}"

export TYPO3_DB_HOST TYPO3_DB_NAME TYPO3_DB_USER TYPO3_DB_PASSWORD TYPO3_PROVISION

case "$TYPO3_PROVISION" in
    auto|wizard) ;;
    *)
        echo "[entrypoint] ERROR: TYPO3_PROVISION must be 'auto' or 'wizard', got '$TYPO3_PROVISION'" >&2
        exit 1
        ;;
esac

case "$TYPO3_BEHIND_TLS" in
    0|1) ;;
    *)
        echo "[entrypoint] ERROR: TYPO3_BEHIND_TLS must be 0 or 1, got '$TYPO3_BEHIND_TLS'" >&2
        exit 1
        ;;
esac

# The trees the Install Tool's directory check requires
# (typo3/sysext/install/mod/class.tx_install.php:2874-2890). Unlike 3.3 there is
# nothing inside the source tree that has to be writable: 4.5 has no typo3/temp/.
for dir in typo3conf typo3temp/pics typo3temp/temp typo3temp/llxml typo3temp/cs \
           typo3temp/GB typo3temp/locks fileadmin/_temp_ uploads/pics uploads/media uploads/tf; do
    mkdir -p "$DOCROOT/$dir"
done
chown -R www-data:www-data "$DOCROOT/typo3conf" "$DOCROOT/typo3temp" "$DOCROOT/fileadmin" "$DOCROOT/uploads"

# --- localconf.php ---------------------------------------------------------
# Written once and then left alone, as in 3.8: the Install Tool edits this file.
LOCALCONF="$DOCROOT/typo3conf/localconf.php"
if [ ! -f "$LOCALCONF" ]; then
    INSTALL_HASH=$(printf '%s' "$TYPO3_INSTALL_PASSWORD" | md5sum | cut -d' ' -f1)

    # Shared by both modes, because the wizard writes the database settings into
    # this same file and the site then has to boot on what it finds here.
    #
    # compat_version is the line a fresh 4.5 cannot boot without. It defaults to
    # '3.8' (t3lib/config_default.php:64), and the UTF-8 block in that file
    # (:725-770) treats any site below '4.5' with no charset of its own as one that
    # was just upgraded — and die()s with "please proceed to the Update Wizard" on
    # every request that is not the Install Tool.
    #
    # trustedHostsPattern is the other half of the TLS fix.
    # The default compares the Host header to SERVER_NAME and to port 443 or 80
    # depending on TYPO3_SSL. Behind the loopback proxy the host carries :8045;
    # behind a TLS proxy with TYPO3_BEHIND_TLS=1, TYPO3 expects 443 while Apache
    # reports 80. Either way every request but the Install Tool's throws
    # UnexpectedValueException 1396795884. '.*' is the decision:
    # the stack answers on loopback only and has no egress, so a forged Host has
    # no one to mislead and nowhere to send mail.
    #
    # extList is the default (t3lib/config_default.php:183) plus t3skin. The default
    # leaves the backend skin out: without it no skin stylesheet is registered, and
    # the backend renders as bare HTML with an unbuilt module menu. 4.5's own
    # update wizard says as much (sysext/install/updates/class.tx_coreupdates_t3skin.php:
    # "Without t3skin the backend may be unusable"). t3skin has no ext_tables.sql, so
    # provision.php's schema is unchanged by it.
    COMMON=$(cat <<EOF
\$TYPO3_CONF_VARS['SYS']['compat_version'] = '4.5';
\$TYPO3_CONF_VARS['EXT']['extList'] = 'filelist,version,tsconfig_help,context_help,extra_page_cm_options,impexp,belog,about,cshmanual,aboutmodules,setup,opendocs,install,t3editor,felogin,feedit,recycler,t3skin';
\$TYPO3_CONF_VARS['SYS']['trustedHostsPattern'] = '.*';
\$TYPO3_CONF_VARS['BE']['installToolPassword'] = '${INSTALL_HASH}';
EOF
)

    if [ "$TYPO3_PROVISION" = wizard ]; then
        echo "[entrypoint] writing stub typo3conf/localconf.php (wizard mode)"
        cat > "$LOCALCONF" <<EOF
<?php
// Generated by 4.5/entrypoint.sh on first boot, in wizard mode.
// Deliberately minimal: the 1-2-3 install wizard fills in the rest.
${COMMON}
?>
EOF
    else
        echo "[entrypoint] writing typo3conf/localconf.php"
        cat > "$LOCALCONF" <<EOF
<?php
// Generated by 4.5/entrypoint.sh on first boot.
// Edit freely — this file is only created when it does not already exist.

\$typo_db_username = '${TYPO3_DB_USER}';
\$typo_db_password = '${TYPO3_DB_PASSWORD}';
\$typo_db_host     = '${TYPO3_DB_HOST}';
\$typo_db          = '${TYPO3_DB_NAME}';

\$TYPO3_CONF_VARS['SYS']['sitename'] = '${TYPO3_SITENAME}';
${COMMON}

// UTF-8, stated rather than inherited. compat_version '4.5' already makes these
// the effective values (t3lib/config_default.php:725-770); writing them out means
// a later change to compat_version cannot quietly turn the connection back into
// latin1, which against this stack's utf8 tables would be the character-set mismatch run
// in the other direction.
\$TYPO3_CONF_VARS['BE']['forceCharset'] = 'utf-8';
\$TYPO3_CONF_VARS['SYS']['setDBinit'] = 'SET NAMES utf8';

// Fixed on purpose, and not a secret — same argument as 3.8: TYPO3 salts
// cHash values with this, and a generated key would put a different hash into
// every frontend URL on every fresh boot.
\$TYPO3_CONF_VARS['SYS']['encryptionKey'] = 'b3e9d1a74c2f8e6051d7a9c3f2b8e4a6d0c5f1e9a7b3d8c2e6f4a0b9d5c1e7f3';

// Image processing. The defaults already point at /usr/bin (:40-41) but still
// name "combine" (:51), which ImageMagick 6 calls "composite". im6 is what
// INSTALL.txt's GraphicsMagick recommendation is the alternative to; the image
// ships ImageMagick 6, as 3.8's does.
\$TYPO3_CONF_VARS['GFX']['im_version_5']        = 'im6';
\$TYPO3_CONF_VARS['GFX']['im_combine_filename'] = 'composite';

// Upstream also lists tiff, pdf and ai. pdf and ai are dropped for 3.8's reason:
// Debian's ImageMagick policy denies the PS and PDF coders and no ghostscript is
// installed, so they would be advertised and broken.
\$TYPO3_CONF_VARS['GFX']['imagefile_ext'] = 'gif,jpg,jpeg,tif,tiff,bmp,pcx,tga,png';
?>
EOF
    fi

    chown www-data:www-data "$LOCALCONF"
    chmod 0640 "$LOCALCONF"
fi

# --- the Install Tool --------------------------------------------------------
# 4.5 locks the Install Tool unless this file exists, and deletes it once it is an
# hour old unless it reads KEEP_FILE (typo3/install/index.php:58, :70-75). Under a
# frozen clock it is not obvious how that age is measured, so the content settles
# it instead. This is what replaces the source edit both older stacks make.
ENABLE_FILE="$DOCROOT/typo3conf/ENABLE_INSTALL_TOOL"
if [ ! -f "$ENABLE_FILE" ]; then
    printf 'KEEP_FILE\n' > "$ENABLE_FILE"
    chown www-data:www-data "$ENABLE_FILE"
fi

# --- database --------------------------------------------------------------
php /usr/local/share/typo3/provision.php

# --- serve -----------------------------------------------------------------
if [ "$TYPO3_BEHIND_TLS" = 1 ]; then
    echo "[entrypoint] starting apache, told it sits behind TLS (HTTPS=on)"
    exec apache2-foreground -DTYPO3_BEHIND_TLS
fi

echo "[entrypoint] starting apache"
exec apache2-foreground
