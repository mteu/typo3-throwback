#!/bin/sh
#
# Boot order: make the writable trees writable, generate localconf.php, provision
# the database, then hand off to Apache.
#
# Same shape as 3.3/entrypoint.sh, and deliberately so — the differences
# between the two are the interesting part. 3.8 needs no FastCGI dance and no
# PATH_TRANSLATED workaround: typo3/init.php:72 reads $_SERVER['SCRIPT_FILENAME']
# for every SAPI that is not cgi/isapi/cgi-fcgi, which mod_php satisfies. So this
# script ends with apache2-foreground rather than spawning a PHP process manager.
set -eu

DOCROOT=/var/www/html

: "${TYPO3_DB_HOST:=db}"
: "${TYPO3_DB_NAME:=typo3}"
: "${TYPO3_DB_USER:=typo3}"
: "${TYPO3_DB_PASSWORD:=typo3}"
: "${TYPO3_SITENAME:=TYPO3 3.8.1}"
: "${TYPO3_INSTALL_PASSWORD:=joh316}"
: "${TYPO3_PROVISION:=auto}"

export TYPO3_DB_HOST TYPO3_DB_NAME TYPO3_DB_USER TYPO3_DB_PASSWORD TYPO3_PROVISION

case "$TYPO3_PROVISION" in
    auto|wizard) ;;
    *)
        echo "[entrypoint] ERROR: TYPO3_PROVISION must be 'auto' or 'wizard', got '$TYPO3_PROVISION'" >&2
        exit 1
        ;;
esac

# The four trees TYPO3 writes to. 3.8 has no typo3/temp/ — the backend renders its
# GD chrome into typo3temp/ instead, which is the one behavioural difference from
# 3.3 that matters for permissions.
for dir in typo3conf typo3temp fileadmin/_temp_ uploads/pics uploads/media uploads/tf; do
    mkdir -p "$DOCROOT/$dir"
done
chown -R www-data:www-data "$DOCROOT/typo3conf" "$DOCROOT/typo3temp" "$DOCROOT/fileadmin" "$DOCROOT/uploads"

# --- localconf.php ---------------------------------------------------------
# t3lib/config_default.php:251 die()s if typo3conf/localconf.php is absent, so
# this file has to exist before anything runs — including the 1-2-3 install
# wizard. It shipped with the separate "dummy" package in 2005; it is generated
# here instead.
#
# Written once and then left alone: the Install Tool edits this same file, and
# regenerating it on every boot would silently discard those edits.
LOCALCONF="$DOCROOT/typo3conf/localconf.php"
if [ ! -f "$LOCALCONF" ]; then
    # t3lib/class.t3lib_install.php authenticates the Install Tool against an md5
    # of the cleartext. joh316 is the historical TYPO3 default.
    INSTALL_HASH=$(printf '%s' "$TYPO3_INSTALL_PASSWORD" | md5sum | cut -d' ' -f1)

    if [ "$TYPO3_PROVISION" = wizard ]; then
        echo "[entrypoint] writing stub typo3conf/localconf.php (wizard mode)"
        cat > "$LOCALCONF" <<EOF
<?php
// Generated by 3.8/entrypoint.sh on first boot, in wizard mode.
// Deliberately minimal: the 1-2-3 install wizard fills in the rest.
\$TYPO3_CONF_VARS['BE']['installToolPassword'] = '${INSTALL_HASH}';
?>
EOF
    else
        echo "[entrypoint] writing typo3conf/localconf.php"
        cat > "$LOCALCONF" <<EOF
<?php
// Generated by 3.8/entrypoint.sh on first boot.
// Edit freely — this file is only created when it does not already exist.

\$typo_db_username = '${TYPO3_DB_USER}';
\$typo_db_password = '${TYPO3_DB_PASSWORD}';
\$typo_db_host     = '${TYPO3_DB_HOST}';
\$typo_db          = '${TYPO3_DB_NAME}';

\$TYPO3_CONF_VARS['SYS']['sitename'] = '${TYPO3_SITENAME}';
\$TYPO3_CONF_VARS['BE']['installToolPassword'] = '${INSTALL_HASH}';

// Fixed on purpose, and not a secret. TYPO3 salts cHash values and other
// checksums with this, so a generated key would put a different hash in every
// rendered frontend URL and break byte-reproducibility. The
// stack is loopback-only and ephemeral, so a published constant costs nothing.
\$TYPO3_CONF_VARS['SYS']['encryptionKey'] = 'c4f7e1ba2d8a4f6b9e0c3d5a7b1f8e2c6d0a9b4e7f3c1d5a8b2e6f0c9d3a7b1e';

// Image processing. 3.8 still ships the 2005 defaults: ImageMagick 4.2.9 under
// /usr/X11R6/bin, whose compositing tool was called "combine". Debian ships
// ImageMagick 6 in /usr/bin, where it is "composite".
\$TYPO3_CONF_VARS['GFX']['image_processing']    = 1;
\$TYPO3_CONF_VARS['GFX']['im_path']             = '/usr/bin/';
\$TYPO3_CONF_VARS['GFX']['im_path_lzw']         = '/usr/bin/';
\$TYPO3_CONF_VARS['GFX']['im_version_5']        = 1;
\$TYPO3_CONF_VARS['GFX']['im_combine_filename'] = 'composite';

// Upstream also lists pdf and ai. Debian's ImageMagick denies the PS and PDF
// coders in /etc/ImageMagick-6/policy.xml (the 2018 Ghostscript CVEs) and no
// ghostscript delegate is installed, so those two are dropped rather than left
// advertised-but-broken. Same call as 3.3.
\$TYPO3_CONF_VARS['GFX']['imagefile_ext'] = 'gif,jpg,jpeg,tif,bmp,pcx,tga,png';

// PHP 5.6 bundles GD 2.x, which is what gdlib_2 asks about. GIF output stays on:
// GD 2 in PHP 5.6 writes GIF again (the LZW patents expired in 2004), so
// GIFBUILDER produces the same format the 2005 backend expected.
\$TYPO3_CONF_VARS['GFX']['gdlib']     = 1;
\$TYPO3_CONF_VARS['GFX']['gdlib_2']   = 1;
\$TYPO3_CONF_VARS['GFX']['gdlib_png'] = 0;
?>
EOF
    fi

    chown www-data:www-data "$LOCALCONF"
    # The Install Tool rewrites this file in place, so the owner needs write.
    chmod 0640 "$LOCALCONF"
fi

# --- database --------------------------------------------------------------
# Waits for the server; in auto mode also builds the schema and seeds content.
php /usr/local/share/typo3/provision.php

# --- serve -----------------------------------------------------------------
echo "[entrypoint] starting apache"
exec apache2-foreground
